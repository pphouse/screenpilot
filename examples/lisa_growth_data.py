def _pick(lst):
    """リストからランダムに1つ選ぶ"""
    return random.choice(lst)


def _pick_product(category=None):
    """商品をランダムに選ぶ (カテゴリ指定可)"""
    pool = [p for p in PRODUCTS if category is None or p["category"] == category]
    if not pool:
        pool = PRODUCTS
    return _pick(pool)



# カテゴリ回転順序 (レビュー系・比較系を増やして購買導線を強化)
CATEGORY_ORDER = [
    "ガチレビュー", "共感系", "比較", "日常+コスメ",
    "ミニレビュー", "購入報告", "ROOM報告", "ランキング",
]


def generate_tweet(category_index: int, history: list[str] | None = None) -> tuple[str, int]:
    """
    カテゴリを回転しながらツイート生成。

    Args:
        category_index: 現在のカテゴリインデックス
        history: 直近のツイート履歴 (重複防止)

    Returns:
        (ツイートテキスト, 次のカテゴリインデックス)
    """
    if history is None:
        history = []

    category = CATEGORY_ORDER[category_index % len(CATEGORY_ORDER)]
    generator = TWEET_GENERATORS[category]

    # 重複防止: 最大5回リトライ
    for _ in range(5):
        tweet = generator()
        if tweet not in history:
            break

    next_index = (category_index + 1) % len(CATEGORY_ORDER)
    return tweet, next_index
